package com.caseo.domain.model;

public class DocumentSet {
    private int id;
    private int orgId;

    public void setId(int id) {
        this.id = id;
    }
    public void setOrgId(int orgId) {
        this.orgId = orgId;
    }

    public int getId() { return id; }
    public int getOrgId() { return orgId; }
}